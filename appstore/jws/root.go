// AppleRootCertificate returns the default trust anchor, Apple Root CA G3.
func AppleRootCertificate() *x509.Certificate {
	block, _ := pem.Decode([]byte(rootPEM))
	certificate, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		panic("jws: invalid embedded Apple Root CA G3")
	}
	return certificate
}
